"""Turn a blockforge project into standalone C++17 or Rust source.

Generated programs use SDL2 for the stage and include their own small runtime,
so they can be copied out of the editor and compiled with a plain compiler.
No Qt, Python, or blockforge installation is needed to run them.
"""

from expressions import ExprContext, translate_expression
from runtime_cpp import SOURCE as CPP_RUNTIME
from runtime_rust import SOURCE as RUST_RUNTIME

# Re-exported so callers only need this module for validation errors.
from core import ValidationError, argument_default, validate_project  # noqa: F401

LANGUAGES = ("cpp", "rust")

_CPP_HEADER = """// Generated by blockforge - {name}
// Target: C++17 + SDL2. Safe to edit; rebuilding from blockforge overwrites it.
#include <SDL2/SDL.h>
#include <algorithm>
#include <array>
#include <atomic>
#include <cctype>
#include <charconv>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <iostream>
#include <mutex>
#include <random>
#include <string>
#include <thread>
#include <unordered_map>
#include <utility>
#include <vector>

"""

_RUST_HEADER = """// Generated by blockforge - {name}
// Target: Rust 2021 + SDL2. Safe to edit; rebuilding from blockforge overwrites it.
#![allow(dead_code, unused_variables, unused_mut)]

"""

_CPP_TYPES = {"number": "double", "text": "const std::string&", "bool": "bool"}
_RUST_TYPES = {"number": "f64", "text": "String", "bool": "bool"}


def _escape(text):
    out = str(text).replace("\\", "\\\\").replace('"', '\\"')
    return out.replace("\n", "\\n").replace("\r", "\\r")


def _literal(text, language):
    if language == "cpp":
        return 'std::string("%s")' % _escape(text)
    return '"%s".to_string()' % _escape(text)


def _number(value, language):
    number = float(value)
    return str(int(number)) if number.is_integer() else str(number)


def _name_literal(text, language):
    """Variable names are &str in Rust and std::string in C++."""
    if language == "cpp":
        return _literal(text, "cpp")
    return '"%s"' % _escape(text)


def _color_value(text, language):
    literal = _literal(text, language)
    if language == "cpp":
        return "Value(%s)" % literal
    return "Value::from(%s)" % literal


def _number_literal(value, language):
    """Rust needs an explicit decimal point for f64 fields."""
    number = float(value)
    if language == "rust" and number.is_integer():
        return "%d.0" % int(number)
    return _number(value, language)


def _costume(sprite):
    """Match the preview's costume clamp in generated initial state."""
    count = max(1, int(sprite.costume_count))
    return max(1, min(count, int(sprite.costume)))


def _context(project, sprite, params=None, locals_=None):
    return ExprContext(
        language=project.language,
        sprite=sprite,
        variables={variable.name: variable.type for variable in project.variables},
        sprites=[item.name for item in project.sprites],
        locals=locals_ or {},
    )


class _Generator:
    def __init__(self, project):
        self.project = project
        self.language = project.language
        self.cpp = project.language == "cpp"
        self.sprite_names = [item.name for item in project.sprites]
        self.procedures = {item.name: item for item in project.procedures}
        self.counter = 0

    def expression(self, source, sprite, locals_=None):
        return translate_expression(
            str(source), _context(self.project, sprite, locals_=locals_)
        )

    def value(self, source, sprite, locals_=None):
        code = self.expression(source, sprite, locals_)
        if self.cpp:
            return "Value(%s)" % code
        return "Value::from(%s)" % code

    def condition(self, source, sprite, locals_=None):
        code = self.expression(source, sprite, locals_)
        if self.cpp:
            return "app.as_bool(Value(%s))" % code
        return "app.as_bool(Value::from(%s))" % code

    def number(self, source, sprite, locals_=None):
        return self.expression(source, sprite, locals_)

    def _next_index(self):
        self.counter += 1
        return self.counter - 1

    def blocks(self, items, sprite, indent=1, locals_=None):
        pad = "    " * indent
        check = ("if (bf_should_stop()) return;" if self.cpp
                 else "if bf_should_stop() { return; }")
        lines = []
        for item in items:
            lines.append(pad + check)
            lines.extend(self.block(item, sprite, indent, locals_))
        if lines and lines[-1].strip() == "{":
            lines.append(pad + "}")
        return lines

    def block(self, item, sprite, indent, locals_=None):
        pad = "    " * indent
        fields = item.fields
        expression = lambda key: self.expression(fields.get(key, ""), sprite, locals_)
        value = lambda key: self.value(fields.get(key, ""), sprite, locals_)
        number = lambda key: self.number(fields.get(key, ""), sprite, locals_)
        sub = lambda slot="SUB": self.blocks(item.children.get(slot, []), sprite,
                                             indent + 1, locals_)
        def call(name, *args):
            if not self.cpp and name == "move":
                name = "move_sprite"
            return "%sapp.%s(%s);" % (
                pad, name, ", ".join(str(arg) for arg in args)
            )
        kind = item.type

        if kind in ("event_flag", "event_key"):
            return []
        if kind == "motion_move":
            return [call("move", sprite, number("steps"))]
        if kind == "motion_turn_right":
            return [call("turn", sprite, number("degrees"))]
        if kind == "motion_turn_left":
            return [call("turn", sprite, "-(%s)" % number("degrees"))]
        if kind == "motion_goto":
            return [call("set_position", sprite, number("x"), number("y"))]
        if kind == "motion_change_x":
            return [call("change_x", sprite, number("value"))]
        if kind == "motion_change_y":
            return [call("change_y", sprite, number("value"))]
        if kind == "motion_set_x":
            return [call("set_x", sprite, number("value"))]
        if kind == "motion_set_y":
            return [call("set_y", sprite, number("value"))]
        if kind == "motion_point_direction":
            return [call("set_direction", sprite, number("direction"))]
        if kind == "motion_point_towards":
            target = fields.get("target", "mouse")
            if target == "mouse":
                index = -1 if self.cpp else "-1isize"
            else:
                index = self.sprite_names.index(target)
            return [call("point_towards", sprite, index)]
        if kind == "motion_glide":
            return [call("glide", sprite, number("x"), number("y"), number("secs"))]
        if kind == "motion_bounce_edge":
            return [call("bounce_edge", sprite)]
        if kind == "looks_say":
            return [call("say", sprite, value("text"), number("secs"))]
        if kind == "looks_show":
            return [call("show", sprite)]
        if kind == "looks_hide":
            return [call("hide", sprite)]
        if kind == "looks_set_size":
            return [call("set_size", sprite, number("size"))]
        if kind == "looks_change_size":
            return [call("change_size", sprite, number("value"))]
        if kind == "looks_set_costume":
            return [call("set_costume", sprite, number("costume"))]
        if kind == "looks_next_costume":
            return [call("next_costume", sprite)]
        if kind == "looks_set_background":
            return [call("set_background", _color_value(
                fields.get("color", "#151a26"), self.language))]
        if kind == "sound_tone":
            return [call("tone", number("freq"), number("secs"))]
        if kind == "sound_stop":
            return [call("stop_tones")]
        if kind == "control_wait":
            return [call("wait", number("secs"))]
        if kind == "control_wait_until":
            condition = self.condition(fields.get("condition", "false"), sprite, locals_)
            if self.cpp:
                return ["%swhile (!%s && app.is_running() && !bf_should_stop()) {"
                        % (pad, condition), call("wait", "0.02"), pad + "}"]
            return ["%swhile !%s && app.is_running() && !bf_should_stop() {"
                    % (pad, condition), call("wait", "0.02"), pad + "}"]
        if kind == "control_repeat":
            index = self._next_index()
            if self.cpp:
                return [
                    "%sdouble bf_count%d = std::min(2147483647.0, "
                    "std::max(0.0, std::round(%s)));" % (
                        pad, index, number("times")),
                    "%sfor (int bf_i%d = 0; bf_i%d < (int)bf_count%d && "
                    "!bf_should_stop(); ++bf_i%d) {"
                    % (pad, index, index, index, index),
                ] + sub() + [pad + "}"]
            return [
                "%slet bf_count%d = ((%s) as f64).round().max(0.0)"
                " .min(i32::MAX as f64) as i32;" % (
                    pad, index, number("times")),
                "%sfor bf_i%d in 0..bf_count%d {" % (pad, index, index),
                "%s    if bf_should_stop() { break; }" % pad,
            ] + sub() + [pad + "}"]
        if kind == "control_forever":
            if self.cpp:
                return ["%swhile (app.is_running() && !bf_should_stop()) {" % pad] + \
                       sub() + [pad + "}"]
            return ["%swhile app.is_running() && !bf_should_stop() {" % pad] + \
                   sub() + [pad + "}"]
        if kind == "control_if":
            return ["%sif (%s) {" % (pad, self.condition(
                fields.get("condition", "true"), sprite, locals_))] + sub() + [pad + "}"]
        if kind == "control_if_else":
            condition = self.condition(fields.get("condition", "true"), sprite, locals_)
            output = ["%sif (%s) {" % (pad, condition)]
            output += self.blocks(item.children.get("THEN", []), sprite,
                                  indent + 1, locals_)
            output.append(pad + "} else {")
            output += self.blocks(item.children.get("ELSE", []), sprite,
                                  indent + 1, locals_)
            output.append(pad + "}")
            return output
        if kind == "control_repeat_until":
            condition = self.condition(fields.get("condition", "false"), sprite, locals_)
            if self.cpp:
                return ["%swhile (!(%s) && app.is_running() && !bf_should_stop()) {"
                        % (pad, condition)] + sub() + [pad + "}"]
            return ["%swhile !(%s) && app.is_running() && !bf_should_stop() {"
                    % (pad, condition)] + sub() + [pad + "}"]
        if kind == "control_stop":
            output = [pad + "bf_stop_script();"]
            if fields.get("choice") == "all":
                output.append(call("stop_all"))
            output.append(pad + "return;")
            return output
        if kind == "control_print":
            return [call("print_line", value("value"))]
        if kind == "variable_set":
            return [call("set_var", _name_literal(fields.get("name", ""), self.language),
                         value("value"))]
        if kind == "variable_change":
            return [call("change_var", _name_literal(fields.get("name", ""), self.language),
                         value("value"))]
        if kind == "variable_if":
            return ["%sif (app.var_bool(%s)) {" % (
                pad, _name_literal(fields.get("name", ""), self.language))] + \
                sub() + [pad + "}"]
        if kind == "pen_clear":
            return [call("pen_clear")]
        if kind == "pen_down":
            return [call("pen_down")]
        if kind == "pen_up":
            return [call("pen_up")]
        if kind == "pen_set_color":
            return [call("pen_set_color", _color_value(
                fields.get("color", "#4ade80"), self.language))]
        if kind == "pen_set_size":
            return [call("pen_set_size", number("size"))]
        if kind == "procedure_call":
            name = fields.get("name", "")
            procedure = self.procedures.get(name)
            if procedure is None:
                return []
            arguments = [self.expression(
                fields.get("arg_%s" % param["name"], argument_default(param)),
                sprite, locals_
            ) for param in procedure.params]
            target = "app" if self.cpp else "app.clone()"
            return ["%sproc_%s(%s, %s%s);" % (
                pad, name, target, sprite,
                "".join(", " + argument for argument in arguments)
            )]
        return [pad + "// blockforge: unknown block %s" % kind]

    def script_function(self, index, script):
        hat = script["blocks"][0]
        name = "script_%d" % index
        sprite = self.sprite_names.index(script["sprite"])
        body = self.blocks(script["blocks"][1:], sprite)
        reset = ("    bf_reset_script();" if self.cpp
                 else "    bf_reset_script();")
        if hat.type != "event_key":
            lines = ["void %s(App& app) {" % name if self.cpp
                     else "fn %s(app: SharedApp) {" % name, reset]
            lines += body + ["}"]
            return lines

        key = hat.fields.get("key", "space")
        from expressions import KEYS
        code = KEYS.get(str(key).lower(), 44)
        if self.cpp:
            return [
                "void %s(App& app) {" % name,
                "    auto body = [&]() {",
                reset,
            ] + ["    " + line for line in body] + [
                "    };",
                "    while (app.is_running()) {",
                "        if (app.key_pressed(%d)) {" % code,
                "            body();",
                "            while (app.key_pressed(%d) && app.is_running()) {" % code,
                "                app.wait(0.02);",
                "            }",
                "        } else {",
                "            app.wait(0.02);",
                "        }",
                "    }",
                "}",
            ]
        return [
            "fn %s_body(app: SharedApp) {" % name,
            reset,
        ] + body + [
            "}",
            "fn %s(app: SharedApp) {" % name,
            "    while app.is_running() {",
            "        if app.key_pressed(%d) {" % code,
            "            %s_body(app.clone());" % name,
            "            while app.key_pressed(%d) && app.is_running() {" % code,
            "                app.wait(0.02);",
            "            }",
            "        } else {",
            "            app.wait(0.02);",
            "        }",
            "    }",
            "}",
        ]

    def procedure_function(self, procedure):
        name = procedure.name
        params = procedure.params
        locals_ = {}
        for param in params:
            code = param["name"]
            if not self.cpp and param["type"] == "text":
                code = "%s.clone()" % code
            locals_[param["name"]] = (param["type"], code)
        if self.cpp:
            signature_params = ", ".join(
                "%s %s" % (_CPP_TYPES[param["type"]], param["name"])
                for param in params
            )
            signature = "void proc_%s(App& app, int sprite%s) {" % (
                name, "".join(", " + part for part in [signature_params] if part)
            )
        else:
            signature_params = ", ".join(
                "%s: %s" % (param["name"], _RUST_TYPES[param["type"]])
                for param in params
            )
            signature = "fn proc_%s(app: SharedApp, sprite: usize%s) {" % (
                name, "".join(", " + part for part in [signature_params] if part)
            )
        return [signature] + self.blocks(procedure.blocks, "sprite", 1, locals_) + ["}"]

    def cpp_main(self):
        lines = [
            "int main(int argc, char** argv) {",
            "    (void)argc; (void)argv;",
            "    if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_AUDIO) != 0) {",
            '        std::cerr << "blockforge: SDL init failed: " << SDL_GetError() << std::endl;',
            "        return 1;",
            "    }",
            '    App app(%d, %d, %s);' % (
                self.project.width, self.project.height,
                _literal(self.project.background, "cpp")),
        ]
        for index, sprite in enumerate(self.project.sprites):
            lines += [
                "    {",
                "        BfSprite item;",
                '        item.name = %s;' % _literal(sprite.name, "cpp"),
                "        item.x = %s;" % _number(sprite.x, "cpp"),
                "        item.y = %s;" % _number(sprite.y, "cpp"),
                "        item.size = %s;" % _number(sprite.size, "cpp"),
                "        item.direction = %s;" % _number(sprite.direction, "cpp"),
                "        item.shape = %s;" % _literal(sprite.shape, "cpp"),
                "        item.color = %s;" % _literal(sprite.color, "cpp"),
                "        item.costume = %d;" % _costume(sprite),
                "        item.costume_count = %d;" % int(sprite.costume_count),
                "        item.layer = %d;" % int(sprite.layer),
                "        item.visible = %s;" % ("true" if sprite.visible else "false"),
                "        app.sprites.push_back(item);",
                "    }",
            ]
        for variable in self.project.variables:
            initial = {"number": "0", "text": 'std::string("")',
                       "bool": "false"}[variable.type]
            lines.append("    app.set_var(%s, Value(%s));" % (
                _name_literal(variable.name, "cpp"), initial))
        lines += [
            "    app.init_audio();",
            '    SDL_Window* window = SDL_CreateWindow(%s.c_str(), SDL_WINDOWPOS_CENTERED, '
            'SDL_WINDOWPOS_CENTERED, app.width, app.height, SDL_WINDOW_SHOWN);'
            % _literal(self.project.name, "cpp"),
            "    if (!window) {",
            '        std::cerr << "blockforge: window failed: " << SDL_GetError() << std::endl;',
            "        app.close_audio();",
            "        SDL_Quit();",
            "        return 1;",
            "    }",
            "    SDL_Renderer* renderer = SDL_CreateRenderer(window, -1, SDL_RENDERER_ACCELERATED);",
            "    if (!renderer) renderer = SDL_CreateRenderer(window, -1, SDL_RENDERER_SOFTWARE);",
            "    if (!renderer) {",
            '        std::cerr << "blockforge: renderer failed: " << SDL_GetError() << std::endl;',
            "        SDL_DestroyWindow(window);",
            "        app.close_audio();",
            "        SDL_Quit();",
            "        return 1;",
            "    }",
            "    std::vector<std::thread> threads;",
        ]
        for index in range(len(self.project.scripts)):
            lines.append("    threads.emplace_back(script_%d, std::ref(app));" % index)
        lines += [
            "    while (app.is_running()) {",
            "        SDL_Event event;",
            "        while (SDL_PollEvent(&event)) {",
            "            if (event.type == SDL_QUIT) app.stop_all();",
            "        }",
            "        app.update_input();",
            "        app.draw(renderer);",
            "        SDL_Delay(16);",
            "    }",
            "    app.stop_all();",
            "    for (std::thread& thread : threads) {",
            "        if (thread.joinable()) thread.join();",
            "    }",
            "    app.close_audio();",
            "    SDL_DestroyRenderer(renderer);",
            "    SDL_DestroyWindow(window);",
            "    SDL_Quit();",
            "    return 0;",
            "}",
        ]
        return lines

    def rust_main(self):
        lines = [
            "fn main() {",
            "    unsafe {",
            "        if SDL_Init(SDL_INIT_VIDEO | SDL_INIT_AUDIO) != 0 {",
            '            eprintln!("blockforge: SDL init failed");',
            "            std::process::exit(1);",
            "        }",
            "    }",
            '    let app: SharedApp = Arc::new(Mutex::new(App::new(%d, %d, %s)));'
            % (self.project.width, self.project.height,
               _name_literal(self.project.background, "rust")),
            "    {",
            "        let mut state = app.lock().unwrap();",
        ]
        for sprite in self.project.sprites:
            lines += [
                '        let mut item = BfSprite::new(%s);' % _name_literal(sprite.name, "rust"),
                "        item.x = %s;" % _number_literal(sprite.x, "rust"),
                "        item.y = %s;" % _number_literal(sprite.y, "rust"),
                "        item.size = %s;" % _number_literal(sprite.size, "rust"),
                "        item.direction = %s;" % _number_literal(sprite.direction, "rust"),
                "        item.shape = %s;" % _literal(sprite.shape, "rust"),
                "        item.color = %s;" % _literal(sprite.color, "rust"),
                "        item.costume = %d;" % _costume(sprite),
                "        item.costume_count = %d;" % int(sprite.costume_count),
                "        item.layer = %d;" % int(sprite.layer),
                "        item.visible = %s;" % ("true" if sprite.visible else "false"),
                "        state.sprites.push(item);",
            ]
        lines.append("    }")
        for variable in self.project.variables:
            initial = {"number": "0.0", "text": 'String::new()',
                       "bool": "false"}[variable.type]
            lines.append("    app.set_var(%s, Value::from(%s));" % (
                _name_literal(variable.name, "rust"), initial))
        lines += [
            "    app.lock().unwrap().init_audio();",
            '    let title = CString::new(%s).unwrap();' % _literal(self.project.name, "rust"),
            "    let (stage_width, stage_height) = {",
            "        let state = app.lock().unwrap();",
            "        (state.width, state.height)",
            "    };",
            "    let window = unsafe {",
            "        SDL_CreateWindow(title.as_ptr(), SDL_WINDOWPOS_CENTERED,",
            "            SDL_WINDOWPOS_CENTERED, stage_width, stage_height,",
            "            SDL_WINDOW_SHOWN)",
            "    };",
            "    if window.is_null() {",
            '        eprintln!("blockforge: window failed");',
            "        app.lock().unwrap().close_audio();",
            "        unsafe { SDL_Quit(); }",
            "        std::process::exit(1);",
            "    }",
            "    let renderer = unsafe {",
            "        SDL_CreateRenderer(window, -1, SDL_RENDERER_ACCELERATED)",
            "    };",
            "    let renderer = if renderer.is_null() {",
            "        unsafe { SDL_CreateRenderer(window, -1, SDL_RENDERER_SOFTWARE) }",
            "    } else { renderer };",
            "    if renderer.is_null() {",
            '        eprintln!("blockforge: renderer failed");',
            "        unsafe { SDL_DestroyWindow(window); SDL_Quit(); }",
            "        app.lock().unwrap().close_audio();",
            "        std::process::exit(1);",
            "    }",
            "    let mut threads = Vec::new();",
        ]
        for index in range(len(self.project.scripts)):
            lines += [
                "    let thread_app = app.clone();",
                "    threads.push(thread::spawn(move || script_%d(thread_app)));" % index,
            ]
        lines += [
            "    let running = app.running_flag();",
            "    while running.load(Ordering::SeqCst) {",
            "        let mut event = BfEvent { bytes: [0u8; 128] };",
            "        unsafe {",
            "            while SDL_PollEvent(event.bytes.as_mut_ptr() as *mut c_void) != 0 {",
            "                let kind = u32::from_ne_bytes([event.bytes[0], event.bytes[1], event.bytes[2], event.bytes[3]]);",
            "                if kind == SDL_QUIT { app.stop_all(); }",
            "            }",
            "        }",
            "        let mut keys = [false; 256];",
            "        unsafe {",
            "            let state = SDL_GetKeyboardState(ptr::null_mut());",
            "            if !state.is_null() {",
            "                for index in 0..256 {",
            "                    keys[index] = *state.add(index) != 0;",
            "                }",
            "            }",
            "        }",
            "        let (mut mouse_x, mut mouse_y) = (0i32, 0i32);",
            "        unsafe { SDL_GetMouseState(&mut mouse_x, &mut mouse_y); }",
            "        app.lock().unwrap().update_input(&keys, (mouse_x, mouse_y));",
            "        app.lock().unwrap().draw(renderer);",
            "        unsafe { SDL_Delay(16); }",
            "    }",
            "    app.stop_all();",
            "    for handle in threads { let _ = handle.join(); }",
            "    app.lock().unwrap().close_audio();",
            "    unsafe {",
            "        SDL_DestroyRenderer(renderer);",
            "        SDL_DestroyWindow(window);",
            "        SDL_Quit();",
            "    }",
            "}",
        ]
        return lines

    def generate(self):
        validate_project(self.project)
        if self.cpp:
            parts = [_CPP_HEADER.format(name=_escape(self.project.name)), CPP_RUNTIME]
        else:
            parts = [_RUST_HEADER.format(name=_escape(self.project.name)), RUST_RUNTIME]
        for procedure in self.project.procedures:
            parts.append("\n".join(self.procedure_function(procedure)))
        for index, script in enumerate(self.project.scripts):
            parts.append("\n".join(self.script_function(index, script)))
        parts.append("\n".join(self.cpp_main() if self.cpp else self.rust_main()))
        return "\n\n".join(part.rstrip() for part in parts) + "\n"


def generate_source(project, language=None):
    """Return standalone source code for *project*."""
    language = language or project.language
    if language not in LANGUAGES:
        raise ValueError("unsupported language: %s" % language)
    from copy import deepcopy
    copy = deepcopy(project)
    copy.language = language
    return _Generator(copy).generate()


def build_command(language, source_path, output_path):
    """Return the compiler argument vector for a generated source file."""
    if language == "cpp":
        return ["g++", "-std=c++17", "-O2", "-pthread", source_path,
                "-o", output_path, "-lSDL2"]
    if language == "rust":
        return ["rustc", "--edition", "2021", "-O", "-A", "dead_code",
                "-A", "unused_variables", source_path, "-o", output_path,
                "-l", "dylib=SDL2"]
    raise ValueError("unsupported language: %s" % language)
