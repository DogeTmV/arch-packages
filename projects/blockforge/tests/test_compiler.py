class NativeParityTests(unittest.TestCase):
    """The generated runtimes must agree with the preview's semantics."""

    def _project(self, *blocks):
        return Project(
            name="Parity",
            scripts=[{"sprite": "Bot", "x": 0, "y": 0, "blocks": [
                block("event_flag"), *blocks,
                block("control_stop", choice="all"),
            ]}],
            sprites=[Sprite(name="Bot")],
        )

    def test_set_costume_clamps_to_the_sprites_costumes(self):
        project = self._project(
            block("looks_set_costume", costume="99"),
            block("control_print", value="costume"),
            block("looks_set_costume", costume="-5"),
            block("control_print", value="costume"),
            block("looks_next_costume"),
            block("control_print", value="costume"),
        )
        for language in ("cpp", "rust"):
            with self.subTest(language=language):
                result = _compile_and_run(project, language)
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertEqual(result.stdout.splitlines(), ["2", "1", "2"])

    def test_touching_edge_uses_the_visible_sprite_radius(self):
        project = self._project(
            block("motion_set_x", value="210"),
            block("control_print", value="touching edge"),
            block("motion_bounce_edge"),
            block("control_print", value="direction"),
        )
        for language in ("cpp", "rust"):
            with self.subTest(language=language):
                result = _compile_and_run(project, language)
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertEqual(result.stdout.splitlines(), ["false", "90"])

    def test_print_normalizes_embedded_and_trailing_newlines(self):
        project = self._project(
            block("control_print", value='"a\\nb\\n"'),
            block("control_print", value='""'),
        )
        for language in ("cpp", "rust"):
            with self.subTest(language=language):
                result = _compile_and_run(project, language)
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertEqual(result.stdout.splitlines(), ["a", "b", ""])

    def test_numeric_helpers_match_the_preview_semantics(self):
        project = self._project(
            block("control_print", value='len("hé")'),
            block("control_print", value='to number("12abc")'),
            block("control_print", value="sqrt(-1)"),
            block("control_print", value="round(-2.5)"),
            block("control_print", value="floor(-1.2)"),
            block("control_print", value="ceil(-1.8)"),
            block("control_print", value="to text(1.0000000001)"),
        )
        expected = ["2", "0", "0", "-3", "-2", "-1", "1.0000000001"]
        for language in ("cpp", "rust"):
            with self.subTest(language=language):
                result = _compile_and_run(project, language)
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertEqual(result.stdout.splitlines(), expected)

    def test_native_runtimes_cap_pen_marks_like_the_preview(self):
        for language in ("cpp", "rust"):
            with self.subTest(language=language):
                source = generate_source(self._project(), language)
                self.assertIn("5000", source)

    def test_native_star_uses_the_same_ten_point_geometry_as_the_stage(self):
        for language in ("cpp", "rust"):
            with self.subTest(language=language):
                source = generate_source(self._project(), language)
                self.assertIn("0.45", source)
                self.assertIn("10", source)


class StageScriptTests(unittest.TestCase):
    def test_a_stage_script_runs_without_a_spirit(self):
        project = Project(
            name="Stage Only", width=160, height=160,
            scripts=[{
                "target": "stage", "x": 24, "y": 24,
                "blocks": [block("event_flag"),
                           block("control_print", value='"stage ready"'),
                           block("control_stop", choice="all")],
            }],
        )
        for language in ("cpp", "rust"):
            with self.subTest(language=language):
                result = _compile_and_run(project, language)
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertIn("stage ready", result.stdout)

    def test_embedded_pictures_compile_into_standalone_programs(self):
        picture = encode_rgba_png(2, 2, bytes([200, 30, 40, 255] * 4))
        backdrop = encode_rgba_png(2, 2, bytes([10, 20, 30, 255] * 4))
        project = Project(
            name="Pictures", width=160, height=160,
            backdrop="backdrop.png",
            sprites=[Sprite(name="Hero", image="hero.png")],
            assets={"hero.png": picture, "backdrop.png": backdrop},
            scripts=[{
                "target": "stage", "x": 0, "y": 0,
                "blocks": [block("event_flag"),
                           block("looks_set_backdrop", backdrop="backdrop.png"),
                           block("control_stop", choice="all")],
            }],
        )
        for language in ("cpp", "rust"):
            with self.subTest(language=language):
                source = generate_source(project, language)
                self.assertIn("add_image", source)
                self.assertIn("set_backdrop", source)
                self.assertIn("200, 30, 40, 255", source)
                result = _compile_and_run(project, language)
                self.assertEqual(result.returncode, 0, result.stderr)


